#!/usr/bin/env python3
"""Regenerate the closed generic ECS snapshot codecs needed by IL2CPP; --check is read-only."""
import argparse
from pathlib import Path
import re

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
target = root / 'Assets/Battle/Simulation/Snapshots/SnapshotAotCatalog.cs'
entries = {}
for path in sorted((root / 'Assets').rglob('*.cs')):
    relative = path.relative_to(root / 'Assets')
    if relative.parts[0] in ('Other', 'Testing') or path == target:
        continue
    source = path.read_text()
    namespaces = list(re.finditer(r'namespace\s+([\w.]+)', source))
    for declaration in re.finditer(r'\bstruct\s+(\w+)\s*:\s*(IComponentData|IBufferElementData)\b', source):
        name, kind = declaration.groups()
        namespace = next((item for item in reversed(namespaces) if item.start() < declaration.start()), None)
        full = (namespace.group(1) + '.' if namespace else '') + name
        entries[full] = 'RegisterComponent' if kind == 'IComponentData' else 'RegisterBuffer'
entries.update({
    'Unity.Entities.Simulate': 'RegisterComponent',
    'Unity.Entities.Disabled': 'RegisterComponent',
    'Unity.Entities.Prefab': 'RegisterComponent',
    'Unity.Entities.LinkedEntityGroup': 'RegisterBuffer',
})
lines = [
    '// <auto-generated> Tools/generate_snapshot_catalog.py </auto-generated>',
    'using System;', 'using System.Collections.Generic;', '',
    'namespace Archeus.Battle.Snapshots', '{',
    '    public static class SnapshotAotCatalog', '    {',
    '        private static readonly HashSet<Type> registered = new();',
    '        private static bool initialized;',
    '        public static bool IsRegistered(Type type) { Register(); return registered.Contains(type); }',
    '        public static void Register()', '        {',
    '            if (initialized) return;',
]
for full, method in sorted(entries.items()):
    lines += [f'            SnapshotComponents.{method}<global::{full}>();',
              f'            registered.Add(typeof(global::{full}));']
lines += ['            initialized = true;', '        }', '    }', '}', '']
output = '\n'.join(lines)
if args.check:
    if not target.is_file() or target.read_text() != output:
        raise SystemExit('Snapshot AOT catalog is stale; run Tools/generate_snapshot_catalog.py')
    print(f'Snapshot AOT catalog covers {len(entries)} component/buffer types')
else:
    target.write_text(output)
    print(f'Generated {len(entries)} snapshot codecs')
